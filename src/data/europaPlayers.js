export const EUROPA_PLAYERS_BY_TEAM = Object.fromEntries(
  Object.entries(RAW_EUROPA_ROSTERS).map(([teamId, rows]) => [
    teamId,
    rows.map(([name, position, nationality, rating], i) => ({
      id: `${teamId}-p${i + 1}`,
      teamId,
      name,
      position,
      nationality,
      rating,
    })),
  ])
);

export function getEuropaPlayersByTeam(teamId) {
  return EUROPA_PLAYERS_BY_TEAM[teamId] || [];
}

export function getAllEuropaPlayers() {
  return Object.values(EUROPA_PLAYERS_BY_TEAM).flat();
}

