export const SUPER_LIG_PLAYERS_BY_TEAM = Object.fromEntries(
  Object.entries(RAW_SUPER_LIG_ROSTERS).map(([teamId, rows]) => [
    teamId,
    rows.map(([name, position, nationality, rating], i) => ({
      id: `${teamId}-p${i + 1}`,
      teamId,
      name,
      position,
      nationality,
      rating,
    })),
  ])
);

export function getSuperLigPlayersByTeam(teamId) {
  return SUPER_LIG_PLAYERS_BY_TEAM[teamId] || [];
}

export function getAllSuperLigPlayers() {
  return Object.values(SUPER_LIG_PLAYERS_BY_TEAM).flat();
}

